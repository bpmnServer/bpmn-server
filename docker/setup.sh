#!/bin/sh
# Interactive installation; writes local .env and optional local image files.
# First run: sh setup.sh. Reconfigure: sh setup.sh --reconfigure.
set -eu
cd "$(dirname "$0")"
mode=${1:-}
if [ -f .env ] && [ "$mode" != "--reconfigure" ]; then
  echo "Existing .env preserved. Use 'sh setup.sh --reconfigure' to change it."
  if [ ! -f up.sh ]; then curl -fL https://raw.githubusercontent.com/bpmnServer/bpmn-server/main/docker/up.sh -o up.sh; fi
  sh up.sh
  exit
fi
old() { if [ -f .env ]; then sed -n "s/^$1=//p" .env | head -n 1; fi; }
ask() {
  label=$1; default=$2
  if [ -t 0 ]; then
    printf '%s [%s]: ' "$label" "$default" >&2
    IFS= read -r answer || answer=
    printf '%s' "${answer:-$default}"
  else printf '%s' "$default"; fi
}
port=$(ask "Host port" "$(old PORT | grep . || printf 3000)")
case "$port" in ''|*[!0-9]*) echo "Invalid port" >&2; exit 2;; esac
[ "$port" -ge 1 ] && [ "$port" -le 65535 ] || { echo "Invalid port" >&2; exit 2; }
database=$(ask "Database (memory/mongo)" "$(case "$(old MONGO_DB_URL)" in mongodb*) printf mongo;; *) printf memory;; esac)")
case "$database" in
  memory) db_url=memory;;
  mongo) db_url=mongodb://mongo:27017/bpmn;;
  *) echo "Choose memory or mongo" >&2; exit 2;;
esac
source=$(ask "Image (published/local)" "$(case "$(old BPMN_IMAGE)" in *:local) printf local;; *) printf published;; esac)")
case "$source" in
  published) image=bpmnserver/bpmn-server:latest;;
  local) image=bpmn-server:local;;
  *) echo "Choose published or local" >&2; exit 2;;
esac
key() { od -An -N24 -tx1 /dev/urandom | tr -d ' \n'; }
secret() { value=$(old "$1"); if [ -n "$value" ]; then printf '%s' "$value"; else key; fi; }
admin=$(old ADMIN_PASSWORD); first=no
if [ -z "$admin" ]; then admin=$(key); first=yes; fi
umask 077
tmp=.env.new.$$
trap 'rm -f "$tmp"' EXIT HUP INT TERM
cat > "$tmp" <<EOF
# Generated by setup.sh. Edit locally; do not commit.
PORT=$port
MONGO_DB_URL=$db_url
BPMN_IMAGE=$image
BPMN_VERSION=${BPMN_VERSION:-latest}
REQUIRE_AUTHENTICATION=true
ENFORCE_SECURITY=true
API_SERVICE_USER_NAME=integration
API_SERVICE_USER_GROUPS=SYSTEM
API_KEY=$(secret API_KEY)
ADMIN_API_KEY=$(secret ADMIN_API_KEY)
SESSION_SECRET=$(secret SESSION_SECRET)
ADMIN_PASSWORD=$admin
EOF
mv "$tmp" .env
chmod 600 .env
trap - EXIT HUP INT TERM
if [ "$first" = yes ]; then echo "Initial admin password: $admin"; fi
compose='docker-compose.yml'
set -- -f "$compose"
if [ "$database" = mongo ]; then
  if [ ! -f docker-compose.mongo.yml ]; then
    curl -fL https://raw.githubusercontent.com/bpmnServer/bpmn-server/main/docker/docker-compose.mongo.yml -o docker-compose.mongo.yml
  fi
  set -- "$@" -f docker-compose.mongo.yml
fi
if [ "$source" = local ]; then
  if [ ! -f docker-compose.build.yml ]; then
    curl -fL https://raw.githubusercontent.com/bpmnServer/bpmn-server/main/docker/docker-compose.build.yml -o docker-compose.build.yml
  fi
  mkdir -p image
  for file in Dockerfile docker-entrypoint.sh; do
    if [ ! -f "image/$file" ]; then
      curl -fL "https://raw.githubusercontent.com/bpmnServer/bpmn-server/main/docker/image/$file" -o "image/$file"
    fi
  done
  echo "Local image files are in ./image; edit and rerun with --build to customize."
  set -- "$@" -f docker-compose.build.yml
fi
echo "Database: $database; image: $source; host port: $port"
docker compose "$@" up -d --build --remove-orphans
echo "Open http://localhost:$port"
