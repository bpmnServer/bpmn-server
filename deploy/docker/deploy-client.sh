#!/usr/bin/env bash
# Install or update ONE isolated BPMN Server client stack (app + MongoDB) on a Docker host.
# Run as root. Application bound to 127.0.0.1 only: publish HTTPS through your reverse proxy.
set -euo pipefail
usage() {
  cat <<'HELP'
Usage: sudo bash deploy/docker/deploy-client.sh CLIENT PORT [IMAGE]
Example: sudo bash deploy/docker/deploy-client.sh acme 3101 ralphhanna/bpmn-web:latest
Creates /opt/bpmn-clients/CLIENT/ with compose.yaml and root-readable .env secrets.
Uses per-client Docker project, named storage volumes and internal DB network.
Re-running updates the image but preserves database, process models and secrets.
HELP
}
[[ $# -ge 2 && $# -le 3 ]] || { usage; exit 2; }
[[ $(id -u) -eq 0 ]] || { echo "Run as root (sudo)" >&2; exit 1; }
client=$1; port=$2; image=${3:-ralphhanna/bpmn-web:latest}
[[ "$client" =~ ^[a-z][a-z0-9-]{0,39}$ ]] || { echo "Invalid client id" >&2; exit 2; }
[[ "$port" =~ ^[0-9]+$ ]] && ((10#$port >= 1024 && 10#$port <= 65535)) || { echo "Invalid port" >&2; exit 2; }
[[ "$image" =~ ^[a-zA-Z0-9][a-zA-Z0-9._/@:-]+$ ]] || { echo "Invalid image reference" >&2; exit 2; }
command -v docker >/dev/null && docker compose version >/dev/null || { echo "Install Docker + Compose first" >&2; exit 1; }
dir="/opt/bpmn-clients/$client"
mkdir -p "$dir"
chmod 700 "$dir"
cd "$dir"
if [[ ! -e .env ]]; then
  umask 077
  key() { openssl rand -hex 32; }
  cat > .env <<EOF
API_KEY=$(key)
ADMIN_API_KEY=$(key)
SESSION_SECRET=$(key)
EOF
  chmod 600 .env
fi
# Do not overwrite an existing tenant with a different image or port without an explicit command.
if [[ -f deployment.conf ]]; then
  # This file is generated by this script, contains validated literal values.
  # Avoid sourcing it as shell code.
  old_port=$(sed -n 's/^PORT=//p' deployment.conf)
  [[ "$old_port" == "$port" ]] || { echo "Existing $client uses port $old_port (requested $port); refusing" >&2; exit 1; }
fi
# Host port must not already be assigned to another client.
for conf in /opt/bpmn-clients/*/deployment.conf; do
  [[ -f "$conf" && "$conf" != "$dir/deployment.conf" ]] || continue
  [[ $(sed -n 's/^PORT=//p' "$conf") != "$port" ]] || { echo "Port $port already allocated: $conf" >&2; exit 1; }
done
cat > compose.yaml <<EOF
name: bpmn-$client
services:
  web:
    image: $image
    ports:
      - "127.0.0.1:$port:3000"
    environment:
      MONGO_DB_URL: mongodb://mongo:27017/bpmn
      REQUIRE_AUTHENTICATION: "true"
      ENFORCE_SECURITY: "true"
      DISABLE_SIGNUP: "true"
      API_SERVICE_USER_NAME: integration
      API_SERVICE_USER_GROUPS: SYSTEM
      API_KEY: \${API_KEY:?missing}
      ADMIN_API_KEY: \${ADMIN_API_KEY:?missing}
      SESSION_SECRET: \${SESSION_SECRET:?missing}
    volumes:
      - processes:/app/processes
    depends_on:
      mongo:
        condition: service_healthy
    restart: unless-stopped
    security_opt:
      - no-new-privileges:true
  mongo:
    image: mongo:8.0
    command: ["--wiredTigerCacheSizeGB", "0.25"]
    volumes:
      - mongodb:/data/db
    healthcheck:
      test: ["CMD", "mongosh", "--quiet", "--eval", "db.adminCommand('ping').ok"]
      interval: 5s
      timeout: 5s
      retries: 30
    restart: unless-stopped
    # MongoDB is only reachable on this client's isolated Compose network.
volumes:
  mongodb:
  processes:
EOF
printf 'PORT=%s\nIMAGE=%s\n' "$port" "$image" > deployment.conf
chmod 600 compose.yaml deployment.conf
docker compose config --quiet
docker compose pull
docker compose up -d --remove-orphans
docker compose ps
echo "Client $client deployed on localhost:$port"
echo "Configure a separate HTTPS reverse-proxy vhost for this client; do NOT open port $port in Lightsail."
echo "IMPORTANT: ensure the application's first admin password is changed BEFORE internet exposure."
echo "Manage: cd $dir; sudo docker compose ps; sudo docker compose logs -f web; sudo docker compose stop/start"
